"""Regenerate THIRD_PARTY_NOTICES.md and LICENSES/ from the installed dependencies.

Run from the repo root after `cd frontend && npm ci` and with the project venv active:

    python tools/make_third_party_notices.py

Lists (1) everything bundled into lineagelens/static (JS, CSS, fonts) with its full licence
text, and (2) the Python runtime dependencies that `pip` installs (not vendored).
"""
from __future__ import annotations

import json
import re
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NM = ROOT / "frontend" / "node_modules"

# Packages whose code or assets end up in the built bundle (lineagelens/static).
BUNDLED = [
    ("react", "UI runtime"), ("react-dom", "UI runtime"), ("scheduler", "dependency of react-dom"),
    ("react-router", "routing"), ("react-router-dom", "routing"), ("@remix-run/router", "dependency of react-router"),
    ("lucide-react", "icons"), ("fuse.js", "fuzzy search"), ("prismjs", "code highlighting"),
    ("clsx", "class names"), ("tailwind-merge", "class names"),
    ("tailwindcss", "generated CSS, including the Preflight base styles"),
    ("vite", "module preload helper injected into the bundle"),
    ("@fontsource-variable/inter", "Inter variable font files (woff2)"),
    ("@fontsource/jetbrains-mono", "JetBrains Mono font files (woff, woff2)"),
]
FONTS = {"@fontsource-variable/inter": "OFL-1.1-Inter.txt", "@fontsource/jetbrains-mono": "OFL-1.1-JetBrains-Mono.txt"}
# Windows-only or optional deps that may not be installed where this script runs.
KNOWN_PY = {"colorama": "BSD-3-Clause"}
SPDX = {"MIT License": "MIT", "ISC License (ISCL)": "ISC", "BSD License": "BSD", "Apache Software License": "Apache-2.0"}
LICENSE_NAMES = ("LICENSE", "LICENSE.md", "LICENSE.txt", "license", "LICENCE", "LICENSE-MIT")


def _license_text(pkg_dir: Path) -> str:
    for n in LICENSE_NAMES:
        if (pkg_dir / n).is_file():
            return (pkg_dir / n).read_text(encoding="utf-8-sig").strip()
    raise SystemExit(f"no licence file in {pkg_dir}")


def _repo(pj: dict) -> str:
    r = pj.get("repository") or pj.get("homepage") or ""
    url = r.get("url", "") if isinstance(r, dict) else r
    url = re.sub(r"^git\+|\.git(#.*)?$|#.*$", "", url).replace("git://", "https://").replace("ssh://git@", "https://")
    if re.fullmatch(r"[\w.-]+/[\w.-]+", url):
        url = "https://github.com/" + url
    return url


def main() -> None:
    if not NM.is_dir():
        sys.exit("run `cd frontend && npm ci` first")
    lic_dir = ROOT / "LICENSES"
    lic_dir.mkdir(exist_ok=True)
    rows, texts = [], []
    for name, why in BUNDLED:
        d = NM / name
        pj = json.loads((d / "package.json").read_text(encoding="utf-8"))
        lic = pj.get("license") or "see licence text"
        text = _license_text(d)
        if name == "vite":  # only Vite's own helper is bundled, not the tools Vite itself bundles
            text = text.split("# Licenses of bundled dependencies")[0].replace("# Vite core license", "").strip()
        rows.append(f"| [{name}]({_repo(pj)}) | {pj['version']} | {lic} | {why} |")
        if name in FONTS:
            (lic_dir / FONTS[name]).write_text(text + "\n", encoding="utf-8", newline="\n")
            texts.append(f"### {name} {pj['version']}\n\nSIL Open Font License 1.1. Full text: [LICENSES/{FONTS[name]}](LICENSES/{FONTS[name]}).\n")
        else:
            texts.append(f"### {name} {pj['version']} ({lic})\n\n```text\n{text}\n```\n")

    py_rows = []
    req = ROOT / "requirements.lock"
    pins = sorted({m.group(1).lower(): m.group(2) for m in re.finditer(r"^([A-Za-z0-9_.-]+)==([^\s;\\]+)", req.read_text(encoding="utf-8"), re.M)}.items())
    for name, ver in pins:
        try:
            md = metadata.metadata(name)
            lic = md.get("License-Expression") or ""
            if not lic:
                cls = [c.split("::")[-1].strip() for c in md.get_all("Classifier") or [] if c.startswith("License ::")]
                lic = ", ".join(cls) or (md.get("License") or "").splitlines()[0][:40]
        except metadata.PackageNotFoundError:
            lic = KNOWN_PY.get(name, "see package metadata")
        lic = SPDX.get(lic, lic)
        py_rows.append(f"| {name} | {ver} | {lic} |")

    out = [
        "# Third-party notices",
        "",
        "LineageLens is MIT licensed (see [LICENSE](LICENSE)). It includes or depends on the third-party software below,",
        "which remains under its own licence. This file is generated by `tools/make_third_party_notices.py`.",
        "",
        "## Bundled in the web UI (`lineagelens/static`)",
        "",
        "These packages are compiled, minified or copied into the files the app serves, so their notices are reproduced here.",
        "",
        "| Package | Version | Licence | Used for |",
        "|---|---|---|---|",
        *rows,
        "",
        "The fonts are licensed under the SIL Open Font License, Version 1.1. They are bundled as the unmodified",
        "`@fontsource` web-font subsets and are not sold on their own. The full licence texts are in [LICENSES/](LICENSES/).",
        "",
        "## Python runtime dependencies (installed by pip, not vendored)",
        "",
        "Installed from PyPI by `pip install` or in the Docker image; each package ships its own licence in its `*.dist-info` folder.",
        "",
        "| Package | Version | Licence |",
        "|---|---|---|",
        *py_rows,
        "",
        "## Licence texts for bundled packages",
        "",
        *texts,
    ]
    (ROOT / "THIRD_PARTY_NOTICES.md").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote THIRD_PARTY_NOTICES.md ({len(rows)} bundled, {len(py_rows)} Python) and LICENSES/")


if __name__ == "__main__":
    main()
